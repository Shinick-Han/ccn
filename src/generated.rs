//! Generated / vendored file detection.
//!
//! A repository's health number must describe *its* code, not a checked-in
//! dependency tree or a protobuf compiler's output (see `docs/PLAN.md` §10).
//! This module is the single place that decides whether a file is one of those,
//! and it is deliberately cheap: it looks at the path and at the first 8 KiB of
//! the bytes the CCN pass already read. It never reads the filesystem itself and
//! never decodes the file as UTF-8.
//!
//! Two independent questions, two independent flags:
//!
//! - **vendored**: is this file part of a third-party tree that was copied in
//!   (`node_modules/`, `vendor/`, `third_party/`, ...)? Paths and filenames
//!   only; no content heuristic can tell a vendored file from a first-party one.
//! - **generated**: was this file produced by a tool? A generator marker in the
//!   head of the file, or a filename that every ecosystem reserves for
//!   generated code (`*.pb.go`, `*.designer.cs`, `*.min.js`, ...).
//!
//! A file can be both (a `*.pb.go` under `vendor/`). Both flags are then set and
//! the vendored reason wins, because "this whole tree is not yours" is the
//! stronger statement. That also means one excluded file is counted in exactly
//! one bucket by [`crate::model::ExcludedFiles`], so
//! `files_analyzed - files_measured == generated + vendored`.
//!
//! ## Accepted false positives
//!
//! - Markers only count when they appear on a **comment line** (`//`, `/*`,
//!   `*`, `#`, `--`, `<!--`, `;`, `%`, `REM`). A test fixture or a source file
//!   that merely quotes a marker inside a string literal is source, not
//!   output. This module contains every marker it searches for and is
//!   deliberately not excluded by itself.
//! - The bare phrase `generated by` is intentionally **not** a marker: it is too
//!   common in prose and in error messages ("value generated by the parser").
//!   Only the specific generator phrasings listed in [`MARKERS`] count.
//! - Directory tokens are matched on whole path segments only, so
//!   `src/vendor.ts` (a first-party file that merely starts with the word) is
//!   **not** vendored. The cost is that a file named exactly `vendor` — no
//!   extension, in a repository that is not vendoring anything — is treated as
//!   a vendored tree. That is rare enough to prefer over trusting the name.
//! - `.map` (source maps) is matched as a suffix, so a hand-written `foo.map`
//!   is excluded. Source maps are generated artifacts in every ecosystem we
//!   care about; a hand-written one is not code we want in the histogram.
//! - A generator that writes its banner as a raw string rather than a comment
//!   (some JSON/XML generators) is missed. That is preferable to excluding a
//!   hand-written source file that happens to mention a marker.

/// How much of a file's head is searched for markers.
///
/// 8 KiB is enough for every generator banner in the wild (license headers that
/// push the banner further are a vendor problem, not ours) and bounds the cost
/// on a 40 MB bundle.
pub const MARKER_SCAN_BYTES: usize = 8 * 1024;

/// What [`classify`] decided about one file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Classification {
    pub is_generated: bool,
    pub is_vendored: bool,
    /// Short, stable reason for the report (`"marker: <phrase>"`,
    /// `"path: node_modules"`). `None` when neither flag is set.
    pub reason: Option<&'static str>,
}

impl Classification {
    /// A first-party source file.
    pub const SOURCE: Self = Self {
        is_generated: false,
        is_vendored: false,
        reason: None,
    };

    pub fn is_excluded(self) -> bool {
        self.is_generated || self.is_vendored
    }
}

/// Directory segment -> reason. Every token is a *whole* path segment (the
/// segment must be followed by another one, i.e. it must be a directory).
const VENDOR_DIRS: &[(&str, &str)] = &[
    ("node_modules", "path: node_modules"),
    ("vendor", "path: vendor"),
    ("third_party", "path: third_party"),
    ("third-party", "path: third-party"),
    ("external", "path: external"),
    ("bower_components", "path: bower_components"),
    (".venv", "path: .venv"),
    ("site-packages", "path: site-packages"),
    ("pods", "path: pods"),
];

/// Filename suffix -> reason. Suffixes, not extensions: `app.min.js` must match
/// without also matching a first-party `min.js`.
const VENDOR_FILES: &[(&str, &str)] = &[
    (".min.js", "path: *.min.js"),
    (".min.css", "path: *.min.css"),
    (".bundle.js", "path: *.bundle.js"),
    (".map", "path: *.map"),
];

/// Filename suffix -> reason, for names that mean "a tool wrote this".
const GENERATED_FILES: &[(&str, &str)] = &[
    (".gen.ts", "path: *.gen.ts"),
    (".gen.tsx", "path: *.gen.tsx"),
    (".g.cs", "path: *.g.cs"),
    (".designer.cs", "path: *.designer.cs"),
    (".pb.go", "path: *.pb.go"),
    (".pb.cc", "path: *.pb.cc"),
    (".pb.h", "path: *.pb.h"),
    ("_pb2.py", "path: *_pb2.py"),
];

/// Marker substring -> reason, checked in this order. More specific phrases
/// come first so a generator banner reports the generator, not the boilerplate.
const MARKERS: &[(&str, &str)] = &[
    ("@generated", "marker: @generated"),
    ("code generated by", "marker: code generated by"),
    ("this file was generated", "marker: this file was generated"),
    (
        "generated by the protocol buffer compiler",
        "marker: generated by the protocol buffer compiler",
    ),
    ("generated automatically", "marker: generated automatically"),
    ("auto-generated", "marker: auto-generated"),
    ("autogenerated", "marker: autogenerated"),
    ("do not edit", "marker: do not edit"),
];

/// Classify one file from its report path and (optionally) its bytes.
///
/// Passing an empty `source` performs the path-only half of the detection: that
/// is what the scan does when it never reads a file (`--no-ccn`, oversize
/// files). Markers are case-insensitive ASCII and are only searched in the first
/// [`MARKER_SCAN_BYTES`] of `source`.
pub fn classify(path: &str, source: &[u8]) -> Classification {
    let vendored = vendored_reason(path);
    let generated = generated_reason(path, source);

    Classification {
        is_generated: generated.is_some(),
        is_vendored: vendored.is_some(),
        // Vendored wins when both apply: see the module docs.
        reason: vendored.or(generated),
    }
}

fn generated_reason(path: &str, source: &[u8]) -> Option<&'static str> {
    filename_reason(path, GENERATED_FILES)
        .or_else(|| generated_dot_infix(path))
        .or_else(|| marker_reason(source))
}

fn vendored_reason(path: &str) -> Option<&'static str> {
    // Walk the segments; a segment is only a directory when another segment
    // follows it, so the last one is always treated as the filename.
    let mut prev: Option<&str> = None;
    for segment in path.split(['/', '\\']).filter(|s| !s.is_empty()) {
        if let Some(dir) = prev {
            if eq_ignore_ascii_case(dir, ".cargo") && eq_ignore_ascii_case(segment, "registry") {
                return Some("path: .cargo/registry");
            }
            if let Some((_, reason)) = VENDOR_DIRS
                .iter()
                .find(|(token, _)| eq_ignore_ascii_case(dir, token))
            {
                return Some(reason);
            }
        }
        prev = Some(segment);
    }

    filename_reason(path, VENDOR_FILES)
}

/// `*.generated.*` cannot be a single suffix because the extension varies
/// (`user.generated.ts`, `schema.generated.proto`).
fn generated_dot_infix(path: &str) -> Option<&'static str> {
    let name = filename(path);
    contains_ignore_ascii_case(name.as_bytes(), b".generated.").then_some("path: *.generated.*")
}

fn filename(path: &str) -> &str {
    path.rsplit(['/', '\\']).next().unwrap_or(path)
}

fn filename_reason(path: &str, patterns: &[(&'static str, &'static str)]) -> Option<&'static str> {
    let name = filename(path);
    patterns
        .iter()
        .find(|(suffix, _)| ends_with_ignore_ascii_case(name, suffix))
        .map(|(_, reason)| *reason)
}

fn marker_reason(source: &[u8]) -> Option<&'static str> {
    let end = source.len().min(MARKER_SCAN_BYTES);
    let head = &source[..end];
    MARKERS
        .iter()
        .find(|(needle, _)| marker_in_comment(head, needle.as_bytes()))
        .map(|(_, reason)| *reason)
}

/// A marker only counts when the line it sits on looks like a comment.
///
/// Generators write their banner in a comment (line comments, block comments,
/// hash comments). Requiring that prefix keeps a source file that merely
/// *mentions* a marker — including this module's own marker table — from being
/// excluded.
fn marker_in_comment(head: &[u8], needle: &[u8]) -> bool {
    if needle.is_empty() {
        return false;
    }
    let mut cursor = 0;
    while let Some(offset) = find_ignore_ascii_case(&head[cursor..], needle) {
        let at = cursor + offset;
        let line_start = head[..at]
            .iter()
            .rposition(|b| *b == b'\n')
            .map_or(0, |p| p + 1);
        if is_comment_prefix(&head[line_start..at]) {
            return true;
        }
        cursor = at + needle.len();
    }
    false
}

fn is_comment_prefix(line_before_marker: &[u8]) -> bool {
    let prefix = line_before_marker.trim_ascii_start();
    [
        b"//".as_slice(),
        b"/*",
        b"*",
        b"#",
        b"--",
        b"<!--",
        b";",
        b"%",
        b"REM ",
        b"rem ",
    ]
    .iter()
    .any(|token| prefix.starts_with(token))
}

/// `b` must be lowercase ASCII.
fn eq_ignore_ascii_case(a: &str, b: &str) -> bool {
    a.len() == b.len()
        && a.bytes()
            .zip(b.bytes())
            .all(|(x, y)| x.to_ascii_lowercase() == y)
}

fn ends_with_ignore_ascii_case(haystack: &str, suffix: &str) -> bool {
    let h = haystack.as_bytes();
    let s = suffix.as_bytes();
    h.len() >= s.len()
        && h[h.len() - s.len()..]
            .iter()
            .zip(s)
            .all(|(x, y)| x.to_ascii_lowercase() == *y)
}

fn contains_ignore_ascii_case(haystack: &[u8], needle: &[u8]) -> bool {
    find_ignore_ascii_case(haystack, needle).is_some()
}

fn find_ignore_ascii_case(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    if needle.is_empty() || haystack.len() < needle.len() {
        return None;
    }
    haystack.windows(needle.len()).position(|window| {
        window
            .iter()
            .zip(needle)
            .all(|(x, y)| x.to_ascii_lowercase() == *y)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cls(path: &str, source: &[u8]) -> Classification {
        classify(path, source)
    }

    #[test]
    fn marker_at_generated_is_recognised() {
        let c = cls("src/grammar.ts", b"// @generated by tooling\n");
        assert!(c.is_generated);
        assert!(!c.is_vendored);
        assert_eq!(c.reason, Some("marker: @generated"));
    }

    #[test]
    fn markers_are_case_insensitive_and_include_the_go_banner() {
        let go = cls(
            "api/handler.go",
            b"// Code Generated By protoc-gen-go. DO NOT EDIT.\n",
        );
        assert!(go.is_generated);
        assert_eq!(go.reason, Some("marker: code generated by"));

        let c = cls("a.cs", b"// this file WAS GENERATED; DO NOT EDIT");
        assert!(c.is_generated);
        assert_eq!(c.reason, Some("marker: this file was generated"));
    }

    #[test]
    fn each_documented_marker_is_detected() {
        for (needle, reason) in MARKERS {
            let body = format!("/* {needle} */\n");
            let c = cls("src/file.txt", body.as_bytes());
            assert!(c.is_generated, "marker {needle:?} missed");
            assert_eq!(c.reason, Some(*reason), "reason for {needle:?}");
        }
    }

    #[test]
    fn markers_beyond_the_head_window_are_ignored() {
        let mut body = vec![b'\n'; MARKER_SCAN_BYTES];
        body.extend_from_slice(b"// @generated");
        let c = cls("src/big.ts", &body);
        assert!(!c.is_generated, "only the first 8 KiB may be searched");
        assert_eq!(c.reason, None);

        // The same marker just inside the window is found.
        let mut body = vec![b'\n'; MARKER_SCAN_BYTES - "// @generated".len()];
        body.extend_from_slice(b"// @generated");
        assert!(cls("src/big.ts", &body).is_generated);
    }

    #[test]
    fn bare_generated_by_is_not_a_marker() {
        let c = cls(
            "src/error.ts",
            b"throw new Error('value generated by the parser')",
        );
        assert!(!c.is_generated, "the bare phrase is too ambiguous");
    }

    #[test]
    fn vendored_directory_segments_are_detected() {
        for (dir, reason) in VENDOR_DIRS {
            let path = format!("src/{dir}/lib/index.js");
            let c = cls(&path, b"");
            assert!(c.is_vendored, "{path} should be vendored");
            assert!(!c.is_generated);
            assert_eq!(c.reason, Some(*reason));
        }
    }

    #[test]
    fn vendored_paths_are_case_insensitive_and_handle_windows_separators() {
        assert!(cls("Node_Modules/pkg/a.js", b"").is_vendored);
        assert!(cls(r"src\Third_Party\zlib\zlib.c", b"").is_vendored);
        let c = cls(r"src\VENDOR\deps\a.js", b"");
        assert_eq!(c.reason, Some("path: vendor"));
    }

    #[test]
    fn cargo_registry_is_matched_as_a_pair_of_segments() {
        let c = cls(
            "C:/Users/dev/.cargo/registry/src/serde-1.0.0/lib.rs",
            b"pub fn f() {}",
        );
        assert!(c.is_vendored);
        assert_eq!(c.reason, Some("path: .cargo/registry"));

        // `.cargo` alone is not a vendored tree.
        assert!(!cls(".cargo/config.toml", b"").is_vendored);
        assert!(!cls("registry/src/a.rs", b"").is_vendored);
    }

    #[test]
    fn a_file_named_vendor_is_not_a_vendor_tree() {
        // The decision documented in the module docs: directory tokens match
        // whole segments that are followed by another segment.
        let c = cls("src/vendor.ts", b"export const x = 1;");
        assert!(!c.is_vendored);
        assert!(!c.is_generated);
        assert_eq!(c.reason, None);

        let c = cls("src/vendor/helpers.ts", b"");
        assert!(c.is_vendored, "the directory form is still caught");
    }

    #[test]
    fn vendored_filenames_match_suffixes_not_extensions() {
        for (path, reason) in [
            ("web/static/app.min.js", "path: *.min.js"),
            ("web/static/APP.MIN.CSS", "path: *.min.css"),
            ("web/static/app.bundle.js", "path: *.bundle.js"),
            ("web/static/app.js.map", "path: *.map"),
        ] {
            let c = cls(path, b"");
            assert!(c.is_vendored, "{path} should be vendored");
            assert_eq!(c.reason, Some(reason), "{path}");
        }
        // A first-party file that merely ends in `min.js`-like text is fine.
        assert!(!cls("src/admin.js", b"").is_vendored);
    }

    #[test]
    fn generated_filenames_cover_the_ecosystem_conventions() {
        for path in [
            "src/api.gen.ts",
            "src/view.gen.tsx",
            "obj/Debug/Form.g.cs",
            "obj/Debug/Form.Designer.cs",
            "proto/user.pb.go",
            "proto/user.pb.cc",
            "proto/user.pb.h",
            "proto/user_pb2.py",
            "src/schema.generated.ts",
        ] {
            let c = cls(path, b"");
            assert!(c.is_generated, "{path} should be generated");
            assert_eq!(
                c.reason.map(|r| r.starts_with("path: ")),
                Some(true),
                "{path} reason"
            );
        }
    }

    #[test]
    fn a_file_can_be_both_and_vendored_wins() {
        let c = cls(
            "vendor/proto/user.pb.go",
            b"// Code generated by protoc-gen-go. DO NOT EDIT.",
        );
        assert!(c.is_generated);
        assert!(c.is_vendored);
        assert_eq!(c.reason, Some("path: vendor"), "vendored reason wins");
    }

    #[test]
    fn invalid_utf8_does_not_stop_marker_detection() {
        let mut body = vec![0xff, 0xfe, 0x80, 0x00, 0xc3];
        body.extend_from_slice(b"\n// autogenerated\n");
        body.extend_from_slice(&[0xff, 0xff]);
        let c = cls("src/blob.ts", &body);
        assert!(c.is_generated);
        assert_eq!(c.reason, Some("marker: autogenerated"));
    }

    #[test]
    fn empty_input_is_source() {
        let c = cls("", b"");
        assert_eq!(c, Classification::SOURCE);
        assert!(!c.is_excluded());
        assert_eq!(c.reason, None);

        // A path with no filename (trailing separator) must not panic.
        assert!(!cls("src/", b"").is_excluded());
        assert!(!cls("\\", b"").is_excluded());
    }

    #[test]
    fn ordinary_source_is_not_flagged() {
        for path in [
            "src/main.rs",
            "src/components/Button.tsx",
            "internal/generated/report.go",
            "pkg/vendor_client/client.go",
            "docs/design.md",
        ] {
            let c = cls(path, b"fn main() { println!(\"hello\"); }\n");
            assert_eq!(c, Classification::SOURCE, "{path} was classified {c:?}");
        }
    }

    #[test]
    fn marker_in_a_string_literal_is_not_generated() {
        // A source file that merely mentions a marker is not tool output.
        let src = br#"const BANNER: &str = "DO NOT EDIT";"#;
        assert_eq!(cls("src/msg.rs", src), Classification::SOURCE);
    }

    #[test]
    fn marker_in_this_modules_own_table_is_not_generated() {
        // The detector contains every marker it searches for; it must not
        // exclude itself (the pre-comment-check version did exactly that).
        let src = br#"    ("do not edit", "marker: do not edit"),"#;
        assert_eq!(cls("src/generated.rs", src), Classification::SOURCE);
    }

    #[test]
    fn marker_in_a_line_comment_is_generated() {
        let go = b"// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage pb\n";
        let c = cls("api/thing.pb.go", go);
        assert!(c.is_generated);
    }

    #[test]
    fn marker_in_a_block_comment_continuation_is_generated() {
        let csharp = b"/*\n * <auto-generated>\n *   This code was generated by a tool.\n */\n";
        let c = cls("Models/Thing.cs", csharp);
        assert!(c.is_generated, "reason: {:?}", c.reason);
    }

    #[test]
    fn marker_in_a_hash_comment_is_generated() {
        let py = b"# This file was generated by the protocol buffer compiler.\n";
        assert!(cls("schema_pb2.py", py).is_generated);
    }
}
