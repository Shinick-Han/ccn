//! `ccn setup nvim` — print or install a Neovim LSP snippet.
//!
//! The snippet starts `ccn lsp` for the languages ccn parses, using the
//! absolute path of the running executable so it also works for npm installs
//! and binaries that are not on `PATH`. Nothing is scanned and no secrets are
//! read.

use std::ffi::OsString;
use std::path::{Path, PathBuf};

/// Environment inputs for the target path. Injected so tests never mutate the
/// process environment.
#[derive(Debug, Clone, Default)]
pub struct TargetEnv {
    pub xdg_config_home: Option<PathBuf>,
    pub local_app_data: Option<PathBuf>,
    pub home: Option<PathBuf>,
    pub is_windows: bool,
}

impl TargetEnv {
    pub fn current() -> Self {
        Self {
            xdg_config_home: std::env::var_os("XDG_CONFIG_HOME").map(PathBuf::from),
            local_app_data: std::env::var_os("LOCALAPPDATA").map(PathBuf::from),
            home: std::env::var_os("HOME").map(PathBuf::from),
            is_windows: cfg!(windows),
        }
    }
}

/// `$XDG_CONFIG_HOME/nvim/after/plugin/ccn.lua`, or the platform config dir.
///
/// On Windows `%LOCALAPPDATA%\nvim\...` is the standard location; on Unix the
/// fallback is `~/.config/nvim/...`.
pub fn target_path(env: &TargetEnv) -> Option<PathBuf> {
    let base = if let Some(xdg) = &env.xdg_config_home {
        xdg.clone()
    } else if env.is_windows {
        env.local_app_data.clone().or_else(|| {
            env.home
                .as_ref()
                .map(|home| home.join("AppData").join("Local"))
        })?
    } else {
        env.home.as_ref()?.join(".config")
    };
    Some(
        base.join("nvim")
            .join("after")
            .join("plugin")
            .join("ccn.lua"),
    )
}

/// Copy-paste Lua for Neovim 0.10+, with the 0.11 `vim.lsp.config` variant
/// documented in a comment.
pub fn snippet(exe: &Path) -> String {
    let exe = lua_string(&exe.display().to_string());
    format!(
        r#"-- Generated by `ccn setup nvim`.
-- Neovim 0.10+: start ccn's LSP once per supported buffer.
--
-- Neovim 0.11+ alternative (replaces the FileType autocmd below):
--   vim.lsp.config("ccn", {{ cmd = {{ "{exe}", "lsp" }}, root_dir = vim.fn.getcwd() }})
--   vim.lsp.enable("ccn")
local ccn = "{exe}"
local filetypes = {{
  "c",
  "cpp",
  "csharp",
  "go",
  "java",
  "javascript",
  "javascriptreact",
  "python",
  "rust",
  "typescript",
  "typescriptreact",
}}

vim.api.nvim_create_autocmd("FileType", {{
  pattern = filetypes,
  callback = function(args)
    vim.lsp.start({{
      name = "ccn",
      cmd = {{ ccn, "lsp" }},
      root_dir = vim.fn.getcwd(),
    }}, {{ bufnr = args.buf }})
  end,
}})
"#
    )
}

/// Escape a path for a double-quoted Lua string.
fn lua_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            _ => out.push(ch),
        }
    }
    out
}

/// Write the snippet, refusing to replace an existing file unless `force`.
fn write_snippet(path: &Path, text: &str, force: bool) -> Result<(), String> {
    if path.exists() && !force {
        return Err(format!(
            "{} already exists; use --force to overwrite it",
            path.display()
        ));
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("could not create {}: {e}", parent.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("could not write {}: {e}", path.display()))
}

fn usage() {
    eprintln!("usage: ccn setup nvim [--print | --write [--force]]");
}

fn help() {
    println!("ccn setup nvim - configure ccn's LSP in Neovim");
    println!();
    println!("usage: ccn setup nvim [--print | --write [--force]]");
    println!();
    println!("  (none)   print a copy-paste Lua snippet");
    println!("  --print  print the snippet explicitly");
    println!("  --write  write it to the Neovim after/plugin directory");
    println!("  --force  allow --write to replace an existing file");
}

/// Entry point for the pre-clap `setup` dispatch. Only `nvim` is supported.
pub fn run(args: &[OsString]) -> i32 {
    let mut command_seen = false;
    let mut write = false;
    let mut force = false;
    let mut print = false;

    for arg in args {
        let text = arg.to_string_lossy();
        match text.as_ref() {
            "nvim" if !command_seen => command_seen = true,
            "--write" => write = true,
            "--force" => force = true,
            "--print" => print = true,
            "-h" | "--help" => {
                help();
                return 0;
            }
            other if other.starts_with('-') => {
                eprintln!("ccn setup: unknown option: {other}");
                usage();
                return 1;
            }
            other => {
                eprintln!("ccn setup: unsupported target: {other} (only `nvim` is supported)");
                usage();
                return 1;
            }
        }
    }

    if !command_seen {
        eprintln!("ccn setup: missing target (only `nvim` is supported)");
        usage();
        return 1;
    }

    let exe = std::env::current_exe().unwrap_or_else(|_| PathBuf::from("ccn"));
    let text = snippet(&exe);

    // No flag at all is the same as `--print`, and `--print --write` does both.
    if print || !write {
        print!("{text}");
    }

    if !write {
        return 0;
    }

    let Some(path) = target_path(&TargetEnv::current()) else {
        eprintln!(
            "ccn setup: cannot determine the Neovim config directory; \
             set XDG_CONFIG_HOME (or LOCALAPPDATA on Windows)"
        );
        return 1;
    };

    match write_snippet(&path, &text, force) {
        Ok(()) => {
            println!("wrote {}", path.display());
            0
        }
        Err(e) => {
            eprintln!("ccn setup: {e}");
            1
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    struct Scratch(PathBuf);

    impl Scratch {
        fn new(name: &str) -> Self {
            let nanos = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos();
            let dir = std::env::temp_dir()
                .join(format!("ccn-setup-{}-{name}-{nanos}", std::process::id()));
            std::fs::create_dir_all(&dir).unwrap();
            Self(dir)
        }
    }

    impl Drop for Scratch {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn xdg_config_home_wins() {
        let env = TargetEnv {
            xdg_config_home: Some(PathBuf::from("/tmp/xdg")),
            local_app_data: Some(PathBuf::from("/tmp/local")),
            home: Some(PathBuf::from("/tmp/home")),
            is_windows: true,
        };
        assert_eq!(
            target_path(&env).unwrap(),
            PathBuf::from("/tmp/xdg/nvim/after/plugin/ccn.lua")
        );
    }

    #[test]
    fn windows_uses_local_app_data_without_xdg() {
        let env = TargetEnv {
            xdg_config_home: None,
            local_app_data: Some(PathBuf::from("C:/Users/me/AppData/Local")),
            home: Some(PathBuf::from("C:/Users/me")),
            is_windows: true,
        };
        assert_eq!(
            target_path(&env).unwrap(),
            PathBuf::from("C:/Users/me/AppData/Local/nvim/after/plugin/ccn.lua")
        );
    }

    #[test]
    fn unix_falls_back_to_home_dot_config() {
        let env = TargetEnv {
            xdg_config_home: None,
            local_app_data: None,
            home: Some(PathBuf::from("/home/me")),
            is_windows: false,
        };
        assert_eq!(
            target_path(&env).unwrap(),
            PathBuf::from("/home/me/.config/nvim/after/plugin/ccn.lua")
        );
    }

    #[test]
    fn target_path_is_none_without_any_config_root() {
        assert_eq!(target_path(&TargetEnv::default()), None);
        let windows = TargetEnv {
            is_windows: true,
            ..TargetEnv::default()
        };
        assert_eq!(target_path(&windows), None);
    }

    #[test]
    fn snippet_uses_the_absolute_binary_and_supported_languages() {
        let text = snippet(Path::new(r"C:\Program Files\ccn\ccn.exe"));
        assert!(text.contains(r#""C:\\Program Files\\ccn\\ccn.exe""#));
        assert!(text.contains(r#"cmd = { ccn, "lsp" }"#));
        assert!(text.contains("root_dir = vim.fn.getcwd()"));
        assert!(text.contains("vim.lsp.config"));
        assert!(text.contains("vim.lsp.enable"));
        for language in ["c", "cpp", "csharp", "go", "java", "python", "rust"] {
            let quoted = format!("\"{language}\"");
            assert!(text.contains(quoted.as_str()), "missing {language}");
        }
        assert!(!text.contains('\u{1b}'));
    }

    #[test]
    fn write_refuses_to_overwrite_without_force() {
        let scratch = Scratch::new("write");
        let path = scratch
            .0
            .join("nvim")
            .join("after")
            .join("plugin")
            .join("ccn.lua");
        write_snippet(&path, "first\n", false).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "first\n");

        let error = write_snippet(&path, "second\n", false).unwrap_err();
        assert!(error.contains("--force"));
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "first\n");

        write_snippet(&path, "second\n", true).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "second\n");
    }
}
